#!/usr/bin/env node
// Regenerates docs/design/tokens.css, the browser-readable mirror of the desktop token contract.
// The contract itself is apps/desktop/src/renderer/styles/globals.css, which a plain file:// page
// cannot read: its values reach components through Tailwind's `@theme inline`, and a design page
// has no Tailwind. So the custom-property blocks are copied out verbatim and the scale `@theme
// inline` derives is written beside them. Run `bun run design:tokens`; docs/design-stack.md says
// so, and a hand-edited mirror is the thing this exists to prevent.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const repositoryRoot = path.resolve(import.meta.dirname, '..')
const contractPath = path.join(repositoryRoot, 'apps/desktop/src/renderer/styles/globals.css')
const inksPath = path.join(repositoryRoot, 'apps/desktop/src/renderer/tokens.css')
const mirrorPath = path.join(repositoryRoot, 'docs/design/tokens.css')

// Each selector's own block, matched on the closing brace at the start of a line so a nested
// `@layer` body cannot end it early. `:root` also appears inside `@theme inline`, so the search
// starts after that block.
export function readBlock(contract, selector) {
  const opened = contract.indexOf(`${selector} {`)
  if (opened === -1) throw new Error(`${contractPath} declares no ${selector} block`)
  const closed = contract.indexOf('\n}', opened)
  if (closed === -1) throw new Error(`the ${selector} block in ${contractPath} never closes`)
  return contract.slice(opened, closed + 2)
}

// The scale `@theme inline` derives: every declaration in it that is not a `--color-*` alias of a
// property the mirrored blocks already carry. Reading them out is what keeps a radius or a size
// added to the contract from being missing here until somebody notices by eye.
export function derivedScale(contract) {
  const block = readBlock(contract, '@theme inline')
  const declared = block.matchAll(/^\s*(--(?!color-)[\w-]+):\s*([^;]+);/gm)
  const lines = [...declared].map(([, name, value]) => `  ${name}: ${value.trim()};`)
  return [':root {', ...lines, '}'].join('\n')
}

// The Sessions inks: a plain `@theme` whose values are the dark appearance, then the light block.
// A design page puts `.dark` on its root element, as the app does, so both copy across verbatim.
export function mirrorInks(inks) {
  return [
    readBlock(inks, '@theme').replace(/^@theme \{/, ':root {'),
    readBlock(inks, ':root:not(.dark)'),
  ]
}

export function mirrorContract(contract, inks) {
  const themed = contract.slice(contract.indexOf('\n}', contract.indexOf('@theme inline')))
  return [
    '/* GENERATED by scripts/design-token-mirror.mjs. Edit the contract, not this file. */',
    readBlock(themed, ':root'),
    readBlock(themed, '.dark'),
    derivedScale(contract),
    ...mirrorInks(inks),
    '',
  ].join('\n\n')
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(
    mirrorPath,
    mirrorContract(readFileSync(contractPath, 'utf8'), readFileSync(inksPath, 'utf8')),
  )
  process.stdout.write(`wrote ${path.relative(repositoryRoot, mirrorPath)}\n`)
}
