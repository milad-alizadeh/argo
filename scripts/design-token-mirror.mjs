#!/usr/bin/env node
// The mirror resolves local contract imports and exposes Tailwind theme declarations as browser custom properties.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const repositoryRoot = path.resolve(import.meta.dirname, '..')
const contractPath = path.join(repositoryRoot, 'apps/desktop/src/renderer/styles/globals.css')
const mirrorPath = path.join(repositoryRoot, 'docs/design/tokens.css')

export function readContract(filePath, ancestors = new Set()) {
  if (ancestors.has(filePath)) throw new Error(`cyclic token contract import: ${filePath}`)
  const importedFrom = new Set([...ancestors, filePath])
  return readFileSync(filePath, 'utf8').replace(
    /^@import ["'](\.[^"']+\.css)["'];$/gm,
    (_, importedPath) =>
      readContract(path.resolve(path.dirname(filePath), importedPath), importedFrom),
  )
}

// Color aliases remain available by the same names that components use in the app.
export function derivedScale(contract) {
  const declared = contract.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)
  const lines = [...declared].map(([, name, value]) => `  ${name}: ${value.trim()};`)
  return [':root {', ...lines, '}'].join('\n')
}

export function mirrorContract(contract) {
  const blocks = [
    ...contract.matchAll(/^(@theme(?: inline)?|:root(?::not\(\.dark\))?|\.dark) \{[\s\S]*?^\}/gm),
  ]
  for (const appearance of [':root', '.dark']) {
    if (!blocks.some(([, selector]) => selector === appearance)) {
      throw new Error(`token contract declares no ${appearance} block`)
    }
  }
  return [
    '/* GENERATED by scripts/design-token-mirror.mjs. Edit the contract, not this file. */',
    ...blocks.map(([block, selector]) =>
      selector.startsWith('@theme') ? derivedScale(block) : block,
    ),
    '',
  ].join('\n\n')
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(mirrorPath, mirrorContract(readContract(contractPath)))
  process.stdout.write(`wrote ${path.relative(repositoryRoot, mirrorPath)}\n`)
}
