/* Merge the per-writer node files into the one file the prototype loads.
   Run: node docs/designs/prototypes/build-content.mjs */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'nodes');

const atlas = {};
for (const file of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
  const part = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  for (const [id, node] of Object.entries(part)) {
    if (atlas[id]) console.warn(`DUPLICATE ${id} — ${file} overwrites an earlier file`);
    atlas[id] = { id, ...node };
  }
}

/* Which part spells which concept is DERIVED, never written down twice. A concept's evidence
   names a file, and a part's anchors name the directories it covers. The longest directory that
   is a prefix of the evidence path owns that concept. Only leaf parts compete, because a
   container's anchors also point into its children's directories and would win every tie. */
const isLeaf = n => n.bottom === true || (n.inside || []).length === 0;
const covers = {};
for (const [id, n] of Object.entries(atlas)) {
  if (n.kind !== 'part' || !isLeaf(n) || n.external) continue;
  covers[id] = [...new Set((n.anchors || []).map(([p]) => p.slice(0, p.lastIndexOf('/'))))];
}
for (const [cid, c] of Object.entries(atlas)) {
  if (c.kind !== 'concept') continue;
  for (const [path] of c.evidence || []) {
    let best = null, bestLen = 0;
    for (const [id, dirs] of Object.entries(covers)) {
      for (const d of dirs) {
        if (path.startsWith(d + '/') && d.length > bestLen) { best = id; bestLen = d.length; }
      }
    }
    if (!best) continue;
    atlas[best].concepts = atlas[best].concepts || [];
    if (!atlas[best].concepts.includes(cid)) atlas[best].concepts.push(cid);
  }
}

/* What runs between a container's children is DERIVED from those children's own `leaving` edges.
   Each entry is [from, to, cargo, sense], and both directions of one pair survive because `sense`
   says which is the data handoff and which is the call. */
for (const [cid, c] of Object.entries(atlas)) {
  if (!(c.inside || []).length) continue;
  const held = new Set(c.inside);
  c.among = c.inside.flatMap(id => (atlas[id]?.leaving || [])
    .filter(([, to]) => held.has(to))
    .map(([, to, cargo, sense]) => [id, to, cargo, sense]));
}

/* Which parts a flow crosses is DERIVED from its own steps, in the order the flow first reaches
   each one. A hand-written list beside the steps drifts from them. */
for (const n of Object.values(atlas)) {
  if (n.kind !== 'flow') continue;
  const seen = [];
  for (const s of n.steps || []) for (const id of [s.from, s.actor, s.to]) {
    if (id && !seen.includes(id)) seen.push(id);
  }
  n.parts = seen;
}

/* A chart cannot draw an id that no node defines, so say so before it renders. */
const known = new Set(Object.keys(atlas));
const dangling = [];
for (const [id, n] of Object.entries(atlas)) {
  for (const field of ['inside', 'concepts', 'parts']) {
    (n[field] || []).forEach(ref => { if (!known.has(ref)) dangling.push(`${id}.${field} → ${ref}`); });
  }
  (n.among || []).forEach(([a, b]) => {
    if (!known.has(a)) dangling.push(`${id}.among → ${a}`);
    if (!known.has(b)) dangling.push(`${id}.among → ${b}`);
  });
  if (n.parent && !known.has(n.parent)) dangling.push(`${id}.parent → ${n.parent}`);
}
dangling.forEach(d => console.warn('DANGLING ' + d));

/* Containment must reach every part, or a part exists that no view can show. */
const reach = new Set(['argo']);
let grew = true;
while (grew) {
  grew = false;
  for (const [id, n] of Object.entries(atlas)) {
    if (n.kind === 'part' && n.parent && reach.has(n.parent) && !reach.has(id)) { reach.add(id); grew = true; }
  }
}
Object.entries(atlas)
  .filter(([id, n]) => n.kind === 'part' && !reach.has(id))
  .forEach(([id]) => console.warn(`UNREACHABLE ${id} — no containment path from argo`));

const counts = {};
Object.values(atlas).forEach(n => { counts[n.kind] = (counts[n.kind] || 0) + 1; });

writeFileSync(join(here, 'atlas-content.js'),
  `/* GENERATED by build-content.mjs from nodes/*.json. Do not edit by hand. */\n` +
  `window.ATLAS = ${JSON.stringify(atlas, null, 2)};\n`);

console.log(`wrote atlas-content.js — ${Object.keys(atlas).length} nodes`, counts,
  dangling.length ? `${dangling.length} dangling` : 'no dangling ids');
